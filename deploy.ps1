# Deploy or update the whole stack, then publish the front end (Windows PowerShell).
# Usage: $env:ANTHROPIC_API_KEY="sk-ant-..."; .\deploy.ps1 -Stack trade-journal -Region us-east-1
param([string]$Stack = "trade-journal", [string]$Region = "us-east-1")
$ErrorActionPreference = "Stop"
Set-Location $PSScriptRoot

if (-not (Get-Command sam -ErrorAction SilentlyContinue)) { throw "Install the AWS SAM CLI first." }
if (-not (Get-Command aws -ErrorAction SilentlyContinue)) { throw "Install the AWS CLI v2 first." }

if (-not (Test-Path samconfig.toml)) {
  Write-Host "First deploy: SAM will ask for a Cognito domain prefix (must be globally unique, lowercase)."
  sam deploy --guided --stack-name $Stack --region $Region --capabilities CAPABILITY_IAM
} else {
  sam deploy --stack-name $Stack --region $Region
}
if ($LASTEXITCODE -ne 0) { throw "sam deploy failed" }

function Out($key) { aws cloudformation describe-stacks --stack-name $Stack --region $Region --query "Stacks[0].Outputs[?OutputKey=='$key'].OutputValue" --output text }

if ($env:ANTHROPIC_API_KEY) {
  aws secretsmanager put-secret-value --region $Region --secret-id (Out "AnthropicSecretArn") --secret-string $env:ANTHROPIC_API_KEY | Out-Null
  Write-Host "Anthropic API key stored in Secrets Manager."
}

if ($env:SCHWAB_APP_KEY -and $env:SCHWAB_APP_SECRET) {
  $sj = @{ appKey = $env:SCHWAB_APP_KEY; appSecret = $env:SCHWAB_APP_SECRET } | ConvertTo-Json -Compress
  aws secretsmanager put-secret-value --region $Region --secret-id (Out "SchwabSecretArn") --secret-string $sj | Out-Null
  Write-Host "Schwab app key stored in Secrets Manager."
}
Write-Host "Schwab callback URL: $(Out 'SchwabCallbackUrl')"

$cfg = @"
// Generated by deploy.ps1 from stack $Stack
window.TJ_CONFIG = {
  apiUrl: "$(Out 'ApiUrl')",
  region: "$Region",
  userPoolId: "$(Out 'UserPoolId')",
  clientId: "$(Out 'UserPoolClientId')",
  cognitoDomain: "$(Out 'CognitoDomain')"
};
"@
Set-Content -Path frontend/config.js -Value $cfg -Encoding UTF8

# stamp the script/style URLs so browsers load the new version right away
$stamp = [DateTimeOffset]::UtcNow.ToUnixTimeSeconds()
$site = Join-Path ([IO.Path]::GetTempPath()) ("tj-site-" + $stamp)
Copy-Item -Recurse -Path frontend -Destination $site
$idx = Join-Path $site "index.html"
(Get-Content $idx -Raw) -replace 'src="app.js"', "src=""app.js?v=$stamp""" -replace 'src="auth.js"', "src=""auth.js?v=$stamp""" -replace 'src="config.js"', "src=""config.js?v=$stamp""" -replace 'href="styles.css"', "href=""styles.css?v=$stamp""" | Set-Content $idx -Encoding UTF8
aws s3 sync $site "s3://$(Out 'SiteBucketName')" --delete --region $Region
aws s3 cp $idx "s3://$(Out 'SiteBucketName')/index.html" --cache-control "no-cache" --content-type "text/html" --region $Region
aws cloudfront create-invalidation --distribution-id (Out "DistributionId") --paths "/*" | Out-Null
Write-Host ""
Write-Host "Done. Open $(Out 'SiteUrl')"
Write-Host "(A brand-new CloudFront distribution can take a few minutes before the URL answers.)"
